  on table public.fc_order_fulfillment_event
  to service_role;
grant usage, select
  on sequence public.fc_order_fulfillment_id_seq
  to service_role;
grant usage, select
  on sequence public.fc_order_fulfillment_event_id_seq
  to service_role;
