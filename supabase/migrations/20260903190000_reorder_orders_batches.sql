-- FC Reorder physical lifecycle.
-- public."order" remains the immutable source of Total Ordered Quantity.

create table if not exists public.reorder_fc_order_state (
  order_id bigint primary key,
  customer_id bigint not null,
  allocation_status text not null default 'ready',
  submitted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reorder_fc_order_state_order_customer_fkey
    foreign key (order_id, customer_id)
    references public."order" (id, customer_id)
    on delete cascade,
  constraint reorder_fc_order_state_status_check
    check (allocation_status in ('ready', 'draft', 'submitted')),
  constraint reorder_fc_order_state_submitted_check
    check (
      (allocation_status = 'submitted' and submitted_at is not null)
      or (allocation_status <> 'submitted' and submitted_at is null)
    ),
  unique (order_id, customer_id)
);

create table if not exists public.reorder_product_allocation (
  id uuid primary key default gen_random_uuid(),
  order_id bigint not null,
  customer_id bigint not null,
  product_version_id uuid not null,
  quantity integer not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint reorder_product_allocation_order_fkey
    foreign key (order_id, customer_id)
    references public."order" (id, customer_id)
    on delete cascade,
  constraint reorder_product_allocation_product_fkey
    foreign key (product_version_id, customer_id)
    references public.reorder_product_version (id, customer_id),
  constraint reorder_product_allocation_quantity_check check (quantity > 0),
  unique (order_id, product_version_id),
  unique (id, order_id, customer_id, product_version_id)
);

