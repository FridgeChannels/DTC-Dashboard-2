create or replace function public.validate_reorder_fc_batch()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_allocation_quantity integer;
  v_existing_quantity bigint;
  v_allocation_status text;
begin
  select allocation.quantity, state.allocation_status
  into v_allocation_quantity, v_allocation_status
  from public.reorder_product_allocation allocation
  join public.reorder_fc_order_state state
    on state.order_id = allocation.order_id
    and state.customer_id = allocation.customer_id
  where allocation.id = new.product_allocation_id
    and allocation.order_id = new.order_id
    and allocation.customer_id = new.customer_id
    and allocation.product_version_id = new.product_version_id
  for update of allocation;

  if not found or v_allocation_status <> 'submitted' then
    raise exception 'Batch requires a submitted Product Allocation';
  end if;

  select coalesce(sum(quantity), 0) into v_existing_quantity
  from public.reorder_fc_batch
  where product_allocation_id = new.product_allocation_id
    and id <> new.id;
  if v_existing_quantity + new.quantity > v_allocation_quantity then
    raise exception 'Batch Quantity cannot exceed Product Allocation Quantity';
  end if;
  return new;
end;
$$;

create trigger validate_reorder_fc_batch_before_write
before insert or update of product_allocation_id, order_id, customer_id,
  product_version_id, quantity
on public.reorder_fc_batch
for each row execute function public.validate_reorder_fc_batch();

create or replace function public.save_reorder_product_allocations(
  p_customer_id bigint,
  p_order_id bigint,
  p_allocations jsonb
)
returns setof public.reorder_product_allocation
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total integer;
  v_allocated bigint;
  v_status text;
  v_count integer;
  v_distinct_count integer;
begin
  if jsonb_typeof(p_allocations) <> 'array' then
    raise exception 'Allocations must be an array';
  end if;

  select quantity into v_total
  from public."order"
  where id = p_order_id and customer_id = p_customer_id
  for update;
  if not found then raise exception 'FC Order not found'; end if;

  insert into public.reorder_fc_order_state (order_id, customer_id)
  values (p_order_id, p_customer_id)
  on conflict (order_id) do nothing;

  select allocation_status into v_status
  from public.reorder_fc_order_state
  where order_id = p_order_id and customer_id = p_customer_id
  for update;
  if v_status = 'submitted' then
    raise exception 'Submitted allocations are locked';
  end if;

  select
    count(*),
    count(distinct (item->>'productVersionId')),
    coalesce(sum((item->>'quantity')::bigint), 0)
  into v_count, v_distinct_count, v_allocated
  from jsonb_array_elements(p_allocations) item;

  if v_count <> v_distinct_count then
    raise exception 'Each Product Version may appear only once';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_allocations) item
    where coalesce(item->>'productVersionId', '') = ''
      or coalesce(item->>'quantity', '') !~ '^[1-9][0-9]*$'
  ) then
    raise exception 'Each allocation requires a Product Version and positive quantity';
  end if;
  if v_allocated > v_total then
    raise exception 'Allocated Quantity cannot exceed Total Ordered Quantity';
  end if;
  if exists (
    select 1
    from jsonb_array_elements(p_allocations) item
    left join public.reorder_product_version product
      on product.id = (item->>'productVersionId')::uuid
      and product.customer_id = p_customer_id
      and product.is_current
      and product.status in ('ready', 'active')
      and product.image_url is not null
    where product.id is null
  ) then
    raise exception 'Select a current, production-ready Product Version';
  end if;

  delete from public.reorder_product_allocation
  where order_id = p_order_id and customer_id = p_customer_id;

  insert into public.reorder_product_allocation (
    order_id, customer_id, product_version_id, quantity
  )
  select
    p_order_id,
    p_customer_id,
    (item->>'productVersionId')::uuid,
    (item->>'quantity')::integer
  from jsonb_array_elements(p_allocations) item;

  update public.reorder_fc_order_state
  set allocation_status = case when v_count = 0 then 'ready' else 'draft' end,
      submitted_at = null
  where order_id = p_order_id and customer_id = p_customer_id;

  insert into public.reorder_audit_log (
    customer_id, entity_type, entity_id, action, after_data
  ) values (
    p_customer_id, 'fc_order', p_order_id::text, 'save_allocation', p_allocations
  );

  return query
  select * from public.reorder_product_allocation
  where order_id = p_order_id and customer_id = p_customer_id
  order by created_at;
end;
$$;

create or replace function public.submit_reorder_product_allocations(
  p_customer_id bigint,
  p_order_id bigint
)
returns public.reorder_fc_order_state
language plpgsql
security definer
set search_path = public
as $$
declare
  v_total integer;
  v_allocated bigint;
  v_result public.reorder_fc_order_state;
begin
  select quantity into v_total
  from public."order"
  where id = p_order_id and customer_id = p_customer_id
  for update;
  if not found then raise exception 'FC Order not found'; end if;

  select coalesce(sum(quantity), 0) into v_allocated
  from public.reorder_product_allocation
  where order_id = p_order_id and customer_id = p_customer_id;
  if v_allocated <> v_total then
    raise exception 'All magnets must be allocated before submission';
  end if;

  insert into public.reorder_fc_order_state (
    order_id, customer_id, allocation_status, submitted_at
  ) values (
    p_order_id, p_customer_id, 'submitted', now()
  )
  on conflict (order_id) do update
    set allocation_status = 'submitted', submitted_at = now()
  returning * into v_result;

  insert into public.reorder_audit_log (
    customer_id, entity_type, entity_id, action, after_data
  ) values (
    p_customer_id,
    'fc_order',
    p_order_id::text,
    'submit_allocation',
    jsonb_build_object('totalOrdered', v_total, 'allocated', v_allocated)
  );

  return v_result;
end;
$$;

create or replace function public.transition_reorder_batch_activation(
  p_customer_id bigint,
  p_batch_id uuid,
  p_from_status text,
  p_to_status text,
  p_scheduled_activation_at timestamptz default null
)
returns public.reorder_fc_batch
language plpgsql
security definer
set search_path = public
as $$
declare
  v_result public.reorder_fc_batch;
  v_production_status text;
  v_product_status text;
  v_product_image text;
begin
  if not (
    (p_from_status = 'draft' and p_to_status in ('scheduled', 'active', 'retired'))
    or (p_from_status = 'scheduled' and p_to_status in ('draft', 'active', 'paused', 'retired'))
    or (p_from_status = 'active' and p_to_status in ('paused', 'retired'))
    or (p_from_status = 'paused' and p_to_status in ('scheduled', 'active', 'retired'))
  ) then
    raise exception 'Invalid Batch activation transition';
  end if;
  if p_to_status = 'scheduled'
    and (p_scheduled_activation_at is null or p_scheduled_activation_at <= now()) then
    raise exception 'Scheduled activation must be a future date and time';
  end if;

  select batch.production_status, product.status, product.image_url
  into v_production_status, v_product_status, v_product_image
  from public.reorder_fc_batch batch
  join public.reorder_product_version product
    on product.id = batch.product_version_id
    and product.customer_id = batch.customer_id
  where batch.id = p_batch_id
    and batch.customer_id = p_customer_id
    and batch.activation_status = p_from_status
  for update of batch;
  if not found then raise exception 'Batch activation changed; refresh and try again'; end if;
  if p_to_status in ('scheduled', 'active')
    and (v_product_status not in ('ready', 'active') or v_product_image is null) then
    raise exception 'Complete the Product Version before activation';
  end if;
  if p_to_status = 'active' and v_production_status not in ('ready', 'shipped') then
    raise exception 'Batch Production must be Ready before activation';
  end if;

  update public.reorder_fc_batch
  set activation_status = p_to_status,
      scheduled_activation_at = case
        when p_to_status = 'scheduled' then p_scheduled_activation_at
        else null
      end
  where id = p_batch_id
    and customer_id = p_customer_id
    and activation_status = p_from_status
  returning * into v_result;
  if not found then raise exception 'Batch activation changed; refresh and try again'; end if;

  insert into public.reorder_audit_log (
    customer_id, entity_type, entity_id, action, before_data, after_data
  ) values (
    p_customer_id,
    'fc_batch',
    p_batch_id::text,
    'activation_transition',
    jsonb_build_object('activationStatus', p_from_status),
    jsonb_build_object(
      'activationStatus', p_to_status,
      'scheduledActivationAt', p_scheduled_activation_at
    )
  );
  return v_result;
end;
$$;

